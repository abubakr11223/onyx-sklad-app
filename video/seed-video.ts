async function makePlaceholder(spec: StoneSpec, file: string): Promise<void> {
  const sharp = (await import("sharp")).default;
  const W = 1200;
  const H = 800;
  const buf = Buffer.alloc(W * H * 3);
  // cheap deterministic "stone": layered sine veins + noise
  let seed = spec.key.split("").reduce((a, c) => a + c.charCodeAt(0), 0);
  const rnd = () => {
    seed = (seed * 1103515245 + 12345) & 0x7fffffff;
    return seed / 0x7fffffff;
  };
  const phase = rnd() * 10;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const v =
        Math.sin((x * 0.006 + y * 0.011) + Math.sin(y * 0.004 + phase) * 2.2) *
          0.5 +
        Math.sin(x * 0.021 - y * 0.007 + phase) * 0.18;
      const t = Math.pow(Math.max(0, v), 6);
      const n = (rnd() - 0.5) * 18;
      const i = (y * W + x) * 3;
      for (let c = 0; c < 3; c++) {
        const val = spec.base[c] * (1 - t) + spec.vein[c] * t + n;
        buf[i + c] = Math.max(0, Math.min(255, Math.round(val)));
      }
    }
  }
  await sharp(buf, { raw: { width: W, height: H, channels: 3 } })
    .blur(1.2)
    .jpeg({ quality: 86 })
    .toFile(file);
}

/** Pick (or generate) the photo file for each stone. */
async function resolveStonePhotos(): Promise<{ byKey: Map<string, string[]>; generated: string[] }> {
  mkdirSync(STONE_ASSETS_DIR, { recursive: true });
  const all = readdirSync(STONE_ASSETS_DIR)
    .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
    .sort();
  const real = all.filter((f) => !f.includes(".placeholder."));
  const used = new Set<string>();
  const byKey = new Map<string, string[]>();
  const generated: string[] = [];
  for (const s of STONES) {
    const hits = real.filter((f) => s.match.some((m) => f.toLowerCase().includes(m)) && !used.has(f));
    hits.forEach((h) => used.add(h));
    if (hits.length > 0) byKey.set(s.key, hits.map((h) => join(STONE_ASSETS_DIR, h)));
  }
  // unmatched real files → stones without a match, in order
  const rest = real.filter((f) => !used.has(f));
  for (const s of STONES) {
    if (byKey.has(s.key)) continue;
    const f = rest.shift();
    if (f) byKey.set(s.key, [join(STONE_ASSETS_DIR, f)]);
  }
  for (const s of STONES) {
    if (byKey.has(s.key)) continue;
    const file = join(STONE_ASSETS_DIR, `${s.key}.placeholder.jpg`);
    if (!existsSync(file)) await makePlaceholder(s, file);
    generated.push(file);
    byKey.set(s.key, [file]);
  }
  return { byKey, generated };
}

