// Demo data for the training-video stand (ТЗ №21 часть Б, «Данные в кадре»).
//
//   npm run video:db
//
// What it does, from scratch, every run:
//   1. DROP + CREATE database `onyx_video` on the local Postgres server that
//      `.env` DATABASE_URL points to (same host/credentials, other database).
//      Never the dev DB `onyx`, never production — see assertVideoDb().
//   2. `prisma migrate deploy` against onyx_video.
//   3. Fills it through the app's own domain functions (intake, sales,
//      reservations, debts/payments, photo requests, leads, collections,
//      batch edit) so remainders, history and audit rows are consistent; then
//      back-dates the rows so the stand looks like ~2 months of real work.
//   4. Writes generated logins to video/.auth.local.json (gitignored).
//
// Env (all optional):
//   VIDEO_DATABASE_URL  full URL of the stand DB (default: .env DATABASE_URL
//                       with database name replaced by `onyx_video`)
//   PHOTO_STORAGE_DIR   forced to video/.photo-store (local photo driver)
// Stone photos: video/assets/stones/*.jpg (generated by another agent). Missing
// → simple placeholder textures are generated next to them (*.placeholder.jpg).
//
// Telegram / AI keys are blanked for this process: nothing leaves the machine.

