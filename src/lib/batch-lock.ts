// Onyx — batch-level pessimistic lock (S2-conc).
// Нормативная база: docs/data-model.md §3 (инвариант «партия доим сходится»),
// §1.6 (BATCH_VOLUME резерв); ADR-005 (свободный остаток НЕ хранится —
// вычисляется из счётчиков Batch + выделенных Slab + прямых Piece).
//
// ПРОБЛЕМА (обзор S2-B). Свободный остаток партии складывается из НЕСКОЛЬКИХ
// входов формулы §3: счётчиков slabsSoldDirect/areaSoldDirectM2 (продажа),
// количества выделенных Slab (выделение плиты) и прямых Piece с
// originSlabId = null (бой без плиты). Разные операции меняют РАЗНЫЕ входы.
// Оптимистический guard в продаже фиксирует в WHERE только sold-direct счётчики,
// поэтому параллельный registerDirectPiece (вставка Piece) с ним НЕ
// конфликтует — и свободный остаток можно увести в минус (аналог двойной
// продажи TZ §7.1 на уровне объёма партии, запрещён §3).
//
// РЕШЕНИЕ — единый пессимистический замок на строку Batch. Каждая транзакция,
// меняющая свободный остаток партии, ПЕРВЫМ делом берёт `SELECT … FOR UPDATE`
// на строку этой партии. Postgres сериализует такие транзакции по одной строке:
// вторая транзакция блокируется до COMMIT первой, а затем читает уже
// обновлённое состояние — то есть guard всегда видит авторитетные данные.

import type { Prisma } from "@prisma/client";

/**
 * Берёт row-level lock (`FOR UPDATE`) на строку партии внутри ТЕКУЩЕЙ
 * транзакции. Должен вызываться ПЕРВЫМ оператором в $transaction — до чтения
 * батча/плит/кусков для расчёта свободного остатка — во всех операциях,
 * которые меняют вход формулы §3 для этой партии (продажа объёма, объёмная
 * бронь, прямой бой без плиты). Замок держится до конца транзакции и
 * освобождается автоматически при COMMIT/ROLLBACK.
 *
 * `${batchId}` параметризуется Prisma в tagged-template $queryRaw (bind-параметр,
 * не конкатенация строки) — SQL-инъекция невозможна. Имя таблицы — "Batch"
 * (PascalCase, без @@map; сверено с prisma/schema.prisma и migration.sql).
 *
 * Если строки с таким id нет, `FOR UPDATE` просто ничего не блокирует (0 строк);
 * последующее findUnique вернёт null, и вызывающий код отдаст свою типовую
 * ошибку NOT_FOUND — здесь мы намеренно не бросаем, чтобы не дублировать
 * контракт ошибок каждого модуля.
 */
export async function lockBatchForUpdate(
  tx: Prisma.TransactionClient,
  batchId: string,
): Promise<void> {
  await tx.$queryRaw`SELECT id FROM "Batch" WHERE id = ${batchId} FOR UPDATE`;
}
