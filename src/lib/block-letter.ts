// ТЗ №7 §2 (BUG-01) → ТЗ №17 §3.1 — нормализация КОДА блока.
//
// Проблема (BUG-01, не изменилась): «B» (лат.) и «В» (кир.) на экране
// неразличимы, но для системы это РАЗНЫЕ места — камень, записанный в один, не
// найдётся в другом. Плюс регистр («a» vs «A») плодит дубли.
//
// Решение ТЗ №7 было: единый алфавит = КИРИЛЛИЦА. ТЗ №17 §3.1 разворачивает его
// в обратную сторону: единый алфавит = ЛАТИНИЦА — так написан бумажный план
// склада (A1, B2, D3, K1, S1…), и коды в системе должны совпадать с тем, что
// зав. склада видит на плане и на самих рядах.
//
// Применяется на ЗАПИСИ (приёмка, разбитие, правка локации, сетка карты) — так
// одна и та же зона всегда пишется одинаково, независимо от раскладки складчика.
//
// ВАЖНО про кириллицу без латинского двойника (Б, Г, Д, Ж, З…): она НЕ
// транслитерируется. «Б» → «B» столкнулось бы с «В» → «B» и молча слило бы два
// РАЗНЫХ блока в один — это хуже дубля. Такие коды остаются как есть, а
// переименование в код с плана (Б → B2 и т. п.) делает зав. склада вручную,
// после физической сверки (ТЗ №17 §4).

/**
 * Кириллица → латиница для визуально одинаковых заглавных букв. Только
 * двойники; кириллические буквы без латинского аналога (Б, Г, Д, Ж, З, И, Й, Л,
 * П, Ф, Ц, Ч, Ш, Щ, Ъ, Ы, Ь, Э, Ю, Я) остаются как есть (в верхнем регистре).
 */
const CYRILLIC_TO_LATIN: Record<string, string> = {
  А: "A",
  В: "B",
  С: "C",
  Е: "E",
  Н: "H",
  К: "K",
  М: "M",
  О: "O",
  Р: "P",
  Т: "T",
  Х: "X",
  У: "Y",
};

/**
 * Нормализует код блока: trim → верхний регистр → кириллические двойники в
 * латиницу. Пустой ввод → "" (валидатор вызывающего сам решит, ошибка это или
 * нет). Многосимвольный ввод обрабатывается посимвольно — это и есть штатный
 * случай ТЗ №17 §3.2: блок теперь целый ряд, код вида «A1», «D3», «S1».
 */
export function normalizeBlockLetter(raw: string): string {
  const upper = raw.trim().toUpperCase();
  let out = "";
  for (const ch of upper) out += CYRILLIC_TO_LATIN[ch] ?? ch;
  return out;
}

/**
 * ТЗ №17 §3.1 — «при вводе кода блока проверять, что введена латиница».
 * Проверяется УЖЕ нормализованный код: двойники к этому моменту стали
 * латиницей, поэтому здесь ловятся только буквы без латинского аналога
 * (Б, Г, Д, Ж…) — то есть реальные остатки старой схемы, которые нужно
 * переименовать руками, а не молча транслитерировать.
 *
 * Разрешены: латинские буквы, цифры, дефис, пробел (например «A1», «K3»,
 * «F1-2»). Пустая строка — не «нелатинская», её отсекает валидатор пустоты.
 */
export function isLatinBlockCode(normalized: string): boolean {
  return /^[A-Z0-9 -]*$/.test(normalized);
}
