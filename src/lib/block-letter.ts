// ТЗ №7 §2 (BUG-01) — нормализация буквы блока. На складе «Блок E» (лат.) и
// «Блок Е» (кир.) визуально одинаковы, но для системы это РАЗНЫЕ места — камень,
// записанный в один, не найдётся в другом (потерянный камень). Плюс регистр
// («a» vs «A») плодит дубли. Решение (выбор владельца): единый алфавит —
// КИРИЛЛИЦА (все существующие блоки уже кириллические, UI русский), + верхний
// регистр. Латинские буквы-двойники приводятся к кириллическим аналогам.
//
// Применяется на ЗАПИСИ (приёмка, разбитие, правка локации, сетка карты) — так
// одна и та же зона всегда пишется одинаково, независимо от раскладки складчика.

/**
 * Латиница → кириллица для визуально одинаковых заглавных букв. Только двойники;
 * латинские буквы без кириллического аналога (D, F, G, J, L, N, Q, R, S, U, V,
 * W, Z) остаются как есть (в верхнем регистре) — их ни с чем не спутать.
 */
const LATIN_TO_CYRILLIC: Record<string, string> = {
  A: "А",
  B: "В",
  C: "С",
  E: "Е",
  H: "Н",
  K: "К",
  M: "М",
  O: "О",
  P: "Р",
  T: "Т",
  X: "Х",
  Y: "У",
};

/**
 * Нормализует букву блока: trim → верхний регистр → латинские двойники в
 * кириллицу. Пустой ввод → "" (валидатор вызывающего сам решит, ошибка это или
 * нет). Многосимвольный ввод обрабатывается посимвольно (на случай «А1» и т.п.).
 */
export function normalizeBlockLetter(raw: string): string {
  const upper = raw.trim().toUpperCase();
  let out = "";
  for (const ch of upper) out += LATIN_TO_CYRILLIC[ch] ?? ch;
  return out;
}
